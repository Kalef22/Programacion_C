/*
Operadores logicos a nivel de bit:
and	= &
or	= |
xor	= ^

*/

#include <stdio.h>

int	main(void)
{
	int	a;
	int b;
	int c;
	int d;
	int e;
	
	a = 378254;
	b = 567123;
	c = a & b;	// AND
	d = a | b;	// OR
	e = a ^ b;	// XOR
	
	printf("%x\n",a);
	printf("%x\n",b);
	printf("%x\n",c);
	printf("%x\n",d);
	printf("%x\n",e);

	return (0);
}

