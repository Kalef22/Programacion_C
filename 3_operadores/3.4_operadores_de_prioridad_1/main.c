/*
Operadores que tienen la maxima prioridad es decir la maxima precedencia:
	() : operador de parentesis:
	 	Para poder modificar la precedencia.
	
	[] : operador de corchete
	 	Para la definición de matrices, arrays, vectores en C tanto de 1
		dimension 2 dimesiones, etc. Tambien se usa para acceder a un
		determinado elemento de una matriz.
	
	-> : operador flecha: 
		Se utiliza para el acceso a un elemento de una determinada estructura
		desde un puntero a esa estructura.
	
	. : operador punto:
		Se utiliza cuando queremos acceder al mientro de una determinada 
		estructura pero en lugar de hacerlo desde un puntero lo hacemos desde
		una variable de esa estructura.
*/